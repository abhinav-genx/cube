import math
from PIL import Image, ImageDraw

# ---------- leaf in a local 100x100 box (y down) ----------
BASE = (50.0, 66.0)
LEAFLETS = [  # (angle deg from "up", length, max half width)
    (0, 52, 5.4), (-26, 48, 5.0), (26, 48, 5.0),
    (-54, 40, 4.4), (54, 40, 4.4), (-84, 29, 3.5), (84, 29, 3.5),
]
TEETH = 9
N = 36  # samples per edge

def leaflet(angle, L, W):
    a = math.radians(angle)
    ux, uy = math.sin(a), -math.cos(a)      # along leaflet (toward tip)
    nx, ny = math.cos(a), math.sin(a)       # perpendicular
    pts = []
    def edge(sign):
        out = []
        for i in range(N + 1):
            t = i / N
            if t == 0:
                w = 0.0
            else:
                base_w = W * (math.sin(math.pi * t) ** 0.62) * (1 - 0.1 * t)
                phase = (t * TEETH) % 1.0
                tooth = 0.95 * (phase if t < 0.93 else 0.0)  # teeth point toward the tip
                w = max(0.0, base_w + tooth - 0.5)
            if t == 1:
                w = 0.0
            d = t * L
            out.append((BASE[0] + ux * d + nx * w * sign, BASE[1] + uy * d + ny * w * sign))
        return out
    right = edge(1)
    left = edge(-1)[::-1]
    return right + left[1:-1]

def path_d():
    parts = []
    for ang, L, W in LEAFLETS:
        pts = leaflet(ang, L, W)
        parts.append("M" + " L".join(f"{x:.1f} {y:.1f}" for x, y in pts) + "Z")
    # stem
    parts.append(f"M48.9 66 L51.1 66 L50.9 84 L49.1 84Z")
    return "".join(parts)

# ---------- cube faces in a 200x200 box ----------
T, R, B, L = (100, 38), (154, 69), (100, 100), (46, 69)
LB, RB, BB = (46, 131), (154, 131), (100, 162)
FACES = {
    "top":   ([T, R, B, L],  (0.54, 0.31, -0.54, 0.31, 100, 38)),
    "left":  ([L, B, BB, LB], (0.54, 0.31, 0, 0.62, 46, 69)),
    "right": ([B, R, RB, BB], (0.54, -0.31, 0, 0.62, 100, 100)),
}
COLORS = {  # face fill, leaf fill
    "top": ("#9DBA97", "#1E3D27"),
    "left": ("#3A6B45", "#E6EEE3"),
    "right": ("#1E3D27", "#9DBA97"),
}

def write_ts():
    with open("components/logoPaths.ts", "w") as f:
        f.write("// Generated by scripts/gen_logo.py — a seven-leaflet leaf in a 100x100 box, and\n")
        f.write("// the three visible faces of an isometric cube in a 200x200 box.\n")
        f.write(f"export const LEAF_D = {path_d()!r};\n\n")
        f.write("export const FACES = {\n")
        for name, (poly, m) in FACES.items():
            pts = " ".join(f"{x},{y}" for x, y in poly)
            f.write(f"  {name}: {{ points: {pts!r}, matrix: {list(m)!r}, face: {COLORS[name][0]!r}, leaf: {COLORS[name][1]!r} }},\n")
        f.write("} as const;\n")

def apply(m, x, y):
    a, b, c, d, e, f = m
    return (a * x + c * y + e, b * x + d * y + f)

def hexrgb(h):
    h = h.lstrip('#'); return tuple(int(h[i:i+2], 16) for i in (0, 2, 4))

def render(size, bg, cube_frac, out):
    S = 4  # supersample
    img = Image.new("RGBA", (size * S, size * S), bg)
    dr = ImageDraw.Draw(img)
    scale = size * S * cube_frac / 200.0
    off = (size * S - 200 * scale) / 2
    def P(x, y): return (off + x * scale, off + y * scale)
    for name, (poly, m) in FACES.items():
        dr.polygon([P(*p) for p in poly], fill=hexrgb(COLORS[name][0]))
    for name, (poly, m) in FACES.items():
        for ang, Lh, W in LEAFLETS:
            pts = [P(*apply(m, x, y)) for x, y in leaflet(ang, Lh, W)]
            dr.polygon(pts, fill=hexrgb(COLORS[name][1]))
        stem = [(48.9, 66), (51.1, 66), (50.9, 84), (49.1, 84)]
        dr.polygon([P(*apply(m, x, y)) for x, y in stem], fill=hexrgb(COLORS[name][1]))
    img = img.resize((size, size), Image.LANCZOS)
    img.save(out)

write_ts()
render(1024, (0xEC, 0xF1, 0xEA, 255), 0.78, "assets/icon.png")
render(1024, (0, 0, 0, 0), 0.60, "assets/adaptive-icon.png")
